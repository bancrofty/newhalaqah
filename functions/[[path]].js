export async function onRequest(context) {
  const res = await context.next();
  try {
    const url = new URL(context.request.url);
    const key = decodeURIComponent(url.pathname).replace(/^\/+|\/+$/g, '');
    const m = Object.prototype.hasOwnProperty.call(META, key) ? META[key] : null;
    const ct = res.headers.get('content-type') || '';
    if (!m || res.status !== 200 || !ct.includes('text/html')) return res;
    const img = SITE + '/' + m.i, link = SITE + '/' + m.u;
    const set = (sel, attr, val) => ({ sel, attr, val });
    const rw = new HTMLRewriter();
    [set('meta[property="og:title"]', 'content', m.t), set('meta[property="og:description"]', 'content', m.d),
     set('meta[property="og:image"]', 'content', img), set('meta[property="og:url"]', 'content', link),
     set('meta[name="description"]', 'content', m.d)]
      .forEach(x => rw.on(x.sel, { element(e) { e.setAttribute(x.attr, x.val); } }));
    rw.on('title', { element(e) { e.setInnerContent(m.t); } });
    return rw.transform(res);
  } catch (err) { return res; }
}
